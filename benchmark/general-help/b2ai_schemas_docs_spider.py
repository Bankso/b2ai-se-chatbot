import os
import re

import scrapy
from markdownify import markdownify as md

# Env var override for the output directory, so smoke tests can write
# somewhere other than output_markdown/ without touching this file.
OUTPUT_DIR_ENV = "B2AI_DOCS_OUTPUT_DIR"

# MkDocs Material appends this to every <title> on the schemas docs site.
TITLE_SUFFIX = " - standards-schema"

ASSET_EXT_RE = re.compile(
    r"\.(css|js|json|png|jpe?g|gif|svg|ico|woff2?|ttf|eot|xml|pdf)$", re.IGNORECASE
)


class B2AISchemasDocsSpider(scrapy.Spider):
    """Crawls the Bridge2AI standards-schema LinkML docs site (MkDocs
    Material, generated by linkml `gen-doc`,
    https://bridge2ai.github.io/standards-schemas/) — the data model
    reference for the registry: classes (DataStandardOrTool, DataSet,
    DataSubstrate, DataTopic, Organization, UseCase, ...), their slots,
    types, and enumerations.

    NOTE: this site's own sitemap.xml (at
    https://bridge2ai.github.io/standards-schemas/sitemap.xml) lists ~150
    URLs under the WRONG base path (singular "standards-schema/", missing
    the trailing "s" that the live site actually uses) — every sitemap URL
    404s. This looks like a site_url mismatch in the LinkML docgen config
    upstream. So this spider does NOT use the sitemap; it crawls from the
    site's own index page instead, which links directly to every
    class/slot/type/enum page from its nav, and that reaches full coverage.
    """

    name = "b2ai_schemas_docs"
    allowed_domains = ["bridge2ai.github.io"]
    BASE_URL = "https://bridge2ai.github.io/standards-schemas/"
    start_urls = [BASE_URL]

    def __init__(self, *args, output_dir=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.output_dir = output_dir or os.environ.get(
            OUTPUT_DIR_ENV, "output_markdown"
        )
        self._seen_filenames = set()

    def _in_scope(self, url):
        if not url.startswith(self.BASE_URL):
            return False
        return not ASSET_EXT_RE.search(url.split("#", 1)[0])

    def _slugify_path(self, url):
        path = url.split("#", 1)[0][len(self.BASE_URL):].strip("/")
        path = path.replace("/", "-")
        return path or "index"

    def _sanitize_title(self, raw_title):
        if not raw_title:
            return None
        title = raw_title.strip()
        if title.endswith(TITLE_SUFFIX):
            title = title[: -len(TITLE_SUFFIX)]
        title = title.strip().replace(" ", "_").replace("/", "-")
        title = re.sub(r"[^\w\-]", "", title)
        return title or None

    def parse(self, response):
        raw_title = response.xpath("//title/text()").get()
        title = self._sanitize_title(raw_title)
        path_slug = self._slugify_path(response.url)
        base_name = title or path_slug

        # Extract the MkDocs Material article content, not the nav/sidebar
        # chrome, falling back progressively if the theme structure changes.
        content_html = (
            response.xpath("//article").get()
            or response.css("div.md-content").get()
            or response.xpath("//main").get()
            or response.xpath("//body").get()
        )
        if content_html:
            markdown_content = md(content_html)
            markdown_with_url = f"source_page_url: {response.url}\n\n{markdown_content}"
            os.makedirs(self.output_dir, exist_ok=True)

            filename = f"b2aischemas_{base_name}.md"
            if filename in self._seen_filenames:
                # Collision — dedupe using the URL path, which is unique.
                filename = f"b2aischemas_{base_name}__{path_slug}.md"
            self._seen_filenames.add(filename)

            file_path = os.path.join(self.output_dir, filename)
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(markdown_with_url)
            self.log(f"Saved file: {file_path}")

        # Follow all internal links under the schemas docs base URL.
        for href in response.css("a::attr(href)").getall():
            next_page = response.urljoin(href).split("#", 1)[0]
            if self._in_scope(next_page):
                yield scrapy.Request(next_page, callback=self.parse)
